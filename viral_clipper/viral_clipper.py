HERE = Path(__file__).resolve().parent
PACKAGE_DIR = HERE / ".viral_clipper"

REQUIREMENTS = [
    ("yt_dlp", "yt-dlp", "downloading from a URL"),
    ("faster_whisper", "faster-whisper", "transcription"),
    ("numpy", "numpy", "fast subject tracking"),
    ("cv2", "opencv-python-headless", "face-aware reframing"),
    ("imageio_ffmpeg", "imageio-ffmpeg", "a bundled ffmpeg, if you have none"),
]


def unpack():
    """Extract the embedded package and put it on the import path."""
    PACKAGE_DIR.mkdir(parents=True, exist_ok=True)
    with gzip.GzipFile(fileobj=io.BytesIO(base64.b64decode(PACKAGE_BLOB))) as gz:
        with tarfile.open(fileobj=gz, mode="r") as tar:
            tar.extractall(PACKAGE_DIR)
    if str(PACKAGE_DIR) not in sys.path:
        sys.path.insert(0, str(PACKAGE_DIR))


def available(module):
    import importlib.util

    try:
        return importlib.util.find_spec(module) is not None
    except (ImportError, ValueError):
        return False


def install():
    """Install everything the full pipeline needs."""
    packages = [pkg for module, pkg, _ in REQUIREMENTS if not available(module)]
    if not packages:
        print("Everything is already installed.")
    else:
        print("Installing:", ", ".join(packages))
        result = subprocess.run(
            [sys.executable, "-m", "pip", "install", "--upgrade", *packages]
        )
        if result.returncode != 0:
            print("\npip failed. Try running this in a virtual environment.")
            return 1

    unpack()
    from clipper.ffmpeg import find_ffmpeg

    binary = find_ffmpeg()
    working = False
    if binary:
        # Finding a path is not proof it runs; check before promising it works.
        try:
            probe = subprocess.run(
                [binary, "-version"], capture_output=True, text=True, timeout=30
            )
            working = probe.returncode == 0
        except Exception:
            working = False

    if working:
        print("\nffmpeg:", binary)
        print("(yt-dlp is handed this path explicitly, so it does not need to be on PATH)")
    elif binary:
        print(f"\nffmpeg was found at {binary} but would not run.")
        print("Install a system one: winget install Gyan.FFmpeg")
    else:
        print(
            "\nffmpeg was not found. Install it with one of:\n"
            "  Windows : winget install Gyan.FFmpeg\n"
            "  macOS   : brew install ffmpeg\n"
            "  Linux   : sudo apt install ffmpeg\n"
            "(the imageio-ffmpeg package just installed also provides one)"
        )
    try:
        import tkinter  # noqa: F401
        window = True
    except ImportError:
        window = False
    print("\nReady.")
    if window:
        print("  python viral_clipper.py                 <- opens the window")
    else:
        print("  (no tkinter in this Python, so the window is unavailable)")
    print("  python viral_clipper.py \"<video url>\" -n 10   <- command line")
    return 0


def main():
    argv = sys.argv[1:]
    if argv and argv[0] in ("--install", "install", "--setup"):
        return install()
    unpack()

    if not argv:
        # No arguments means "just open the app" - which is what most people
        # double-clicking this file expect.
        try:
            from clipper.gui import launch
        except ImportError as exc:
            print(f"Could not start the window: {exc}")
            print("Run `python viral_clipper.py --install` first.")
            return 1
        return launch()

    from clipper.cli import main as cli_main

    # Default to ten clips, which is what most people want, while leaving an
    # explicit -n on the command line in charge.
    if not any(a in ("-n", "--max-clips") for a in argv):
        argv += ["-n", "10"]
    return cli_main(argv)


if __name__ == "__main__":
    raise SystemExit(main())
